// Bake assets/buttons/*.png into src/buttons.rs as packed 0xAARRGGBB sprites.
// 0 = transparent (keep what is under it).
//
// Called by build.rs (when missing) and by examples/gen_buttons.rs.
//
// cargo run -p fluyer-pxui --release --example gen_buttons

use std::fs;
use std::io::BufWriter;
use std::path::Path;
use std::fmt::Write as _;

const SRC: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../../assets/buttons");
const OUT: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/src/buttons.rs");

struct Sprite {
    name: String,
    w: i32,
    h: i32,
    frames: usize,
    px: Vec<u32>,
}

fn load(path: &Path) -> Option<Sprite> {
    let file = fs::File::open(path).ok()?;
    let mut dec = png::Decoder::new(std::io::BufReader::new(file));
    dec.set_transformations(png::Transformations::normalize_to_color8());
    let mut reader = dec.read_info().ok()?;
    let mut buf = vec![0; reader.output_buffer_size()];
    let info = reader.next_frame(&mut buf).ok()?;
    assert!(info.bit_depth == png::BitDepth::Eight, "{path:?}: need 8-bit");
    let ch = info.color_type.samples();
    assert!(ch >= 3, "{path:?}: need rgb(a)");

    let (w, h) = (info.width as i32, info.height as i32);
    // Square frames side by side: width / height frames in one row. A square sheet
    // (e.g. one 9-slice plank) is a single frame.
    let (fw, fh, frames) = (h, h, (w / h) as usize);
    assert_eq!(w % h, 0, "{path:?}: {w}x{h} is not square frames");

    let mut px: Vec<u32> = Vec::with_capacity((fw * fh * frames as i32) as usize);
    for f in 0..frames {
        for y in 0..fh {
            for x in 0..fw {
                let i = ((y * w + x + f as i32 * fw) * ch as i32) as usize;
                let a = if ch == 4 { buf[i + 3] } else { 255 };
                // 0xAARRGGBB; fully transparent pixels become 0 and are skipped on blit.
                px.push(if a < 8 {
                    0
                } else {
                    ((a as u32) << 24)
                        | ((buf[i] as u32) << 16)
                        | ((buf[i + 1] as u32) << 8)
                        | buf[i + 2] as u32
                });
            }
        }
    }

    let name = path.file_stem()?.to_str()?.to_ascii_uppercase().replace('-', "_");
    Some(Sprite { name, w: fw, h: fh, frames, px })
}

pub fn run() {
    let mut sprites: Vec<Sprite> = Vec::new();
    let mut entries: Vec<_> = fs::read_dir(SRC).expect("assets/buttons").flatten().collect();
    entries.sort_by_key(|e| e.path());
    for e in entries {
        let p = e.path();
        if p.extension().and_then(|x| x.to_str()) == Some("png") {
            sprites.push(load(&p).unwrap_or_else(|| panic!("{p:?}: decode failed")));
        }
    }
    assert!(!sprites.is_empty(), "no sprites in {SRC}");

    let mut s = String::new();
    s.push_str("// Generated by crates/pxui/gen/buttons.rs from assets/buttons/ — do not edit.\n");
    s.push_str("// One u32 per pixel: 0xAARRGGBB, 0 = transparent.\n\n");
    for sp in &sprites {
        let n = &sp.name;
        writeln!(s, "pub const {n}_W: i32 = {};", sp.w).unwrap();
        writeln!(s, "pub const {n}_H: i32 = {};", sp.h).unwrap();
        writeln!(s, "pub const {n}_FRAMES: usize = {};", sp.frames).unwrap();
        writeln!(s, "pub static {n}: [u32; {}] = [", sp.px.len()).unwrap();
        for row in sp.px.chunks(sp.w as usize) {
            let line: Vec<String> = row.iter().map(|b| format!("0x{b:08x}")).collect();
            writeln!(s, "    {},", line.join(", ")).unwrap();
        }
        s.push_str("];\n\n");
    }

    fs::write(OUT, s).unwrap();
    let bytes: usize = sprites.iter().map(|s| s.px.len()).sum();
    println!(
        "{:?} -> {OUT} bytes={bytes}",
        sprites.iter().map(|s| (s.name.clone(), s.w, s.h, s.frames)).collect::<Vec<_>>()
    );
    let _ = BufWriter::new(std::io::sink());
}
